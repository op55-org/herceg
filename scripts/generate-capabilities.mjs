// Writes docs/capabilities.md and docs/capabilities.json from the contract
// declarations (test/contracts/) and a complete passing check of them
// (scripts/check-contracts.mjs: every suite, every browser engine), so the
// documented matrix says only what tests prove:
//
//   node scripts/generate-capabilities.mjs           write them
//   node scripts/generate-capabilities.mjs --check   fail if they are stale
//
// Neither holds anything of the run (revision, times, paths outside the
// repository), so they change only when what is proved changes.

import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parseArgs } from "node:util";
import { checkContracts } from "./check-contracts.mjs";
import { root } from "./contracts/source.mjs";

const MD = join(root, "docs/capabilities.md");
const JSON_PATH = join(root, "docs/capabilities.json");

const STATES = { works: "✓", unproved: "○", refused: "✗", na: "·" };

/** The test files proving each contract ID, relative to docs/. */
function proofFiles(executions) {
  const files = new Map();
  for (const { id, suite, test } of executions) {
    // Python's tests are named by module (tests.test_capabilities), Vitest's by path.
    const path =
      suite === "python"
        ? `python/${test.split("::")[0].replaceAll(".", "/")}.py`
        : test.split(" > ")[0];
    files.set(id, relative(join(root, "docs"), join(root, path)));
  }
  return files;
}

/** The documented matrix: every cell with its state, details, and proofs. */
export function capabilityRecords({ declarations, cells, proofs, executions }) {
  const files = proofFiles(executions);
  const proofOf = (id) => ({ id, file: files.get(id) });
  // An unproved cell's awaited proof is none yet.
  const proofsOf = (name) =>
    proofs.filter((proof) => proof.for === name && !proof.unproved).map(({ id }) => proofOf(id));
  const tableOf = (table, rows) =>
    Object.fromEntries(
      Object.entries(rows).map(([row, { title, inventory }]) => [
        row,
        {
          title,
          inventory,
          cells: Object.fromEntries(
            cells
              .filter((cell) => cell.table === table && cell.row === row)
              .map(({ capability, state, error, alternative, reason }) => [
                capability,
                {
                  state,
                  ...(error && {
                    error,
                    alternative: { ...alternative, proofs: alternative.proofs.map(proofOf) },
                  }),
                  ...(reason && { reason }),
                  proofs: proofsOf(`${table} ${row} ${capability}`),
                },
              ]),
          ),
        },
      ]),
    );
  const { capabilities, marks, express, interaction, api } = declarations;
  // Every cell of the matrix, marks' and Express recipes', by state.
  const totals = Object.fromEntries(Object.keys(STATES).map((state) => [state, 0]));
  for (const { state } of cells) totals[state]++;
  return {
    about:
      "Generated by scripts/generate-capabilities.mjs from test/contracts/ and a complete passing run of every test suite; do not edit.",
    totals,
    groups: capabilities.groups,
    capabilities: capabilities.capabilities,
    marks: tableOf("marks", marks.rows),
    express: { capabilities: express.capabilities, recipes: tableOf("express", express.recipes) },
    interaction: {
      placements: interaction.placements,
      cells: interaction.cells.map((id) => ({ id, file: files.get(`${id}.engine`) })),
    },
    gpu: {
      about: capabilities.gpu.about,
      paths: Object.fromEntries(
        Object.entries(capabilities.gpu.paths).map(([path, { title, when, proofs: ids }]) => [
          path,
          { title, when, proofs: ids.map(proofOf) },
        ]),
      ),
    },
    api: { conventions: api.about[0], audits: api.audits },
  };
}

/** One difference of an API audit, as a list item. */
function differenceText(kind, option, entry) {
  const reason = typeof entry === "string" ? entry : entry.reason;
  // "*" is any string; none, names of no choices (a number, a flag).
  const choicesOf = (takes) =>
    takes.length === 0
      ? "no named choices"
      : takes.map((choice) => (choice === "*" ? "any string" : `"${choice}"`)).join(", ");
  switch (kind) {
    case "spelled":
      return `\`${option}\` is \`${entry.as}\`: ${reason}`;
    case "spread": {
      const as = Object.entries(entry.as ?? {}).map(([from, to]) => `${from} is \`${to}\``);
      return `\`${option}\`'s settings are options of their own${as.length ? ` (${as.join(", ")})` : ""}: ${reason}`;
    }
    case "without":
      return `no \`${option}\`: ${reason}`;
    case "only":
      return `\`${option}\`, its own: ${reason}`;
    case "choices":
      return `\`${option}\` takes ${choicesOf(entry.takes)}: ${reason}`;
    case "untyped":
      return `\`${option}\`'s settings are typed on one side alone: ${reason}`;
    default:
      throw new Error(`api.json: no difference of kind ${kind}`);
  }
}

const cellText = (text) => text.replaceAll("|", "\\|");

/** A line with what Markdown would read as HTML (`<Chart>`) written as text, outside code spans. */
const escapeTags = (line) =>
  line
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replaceAll("<", "&lt;")))
    .join("");

/** A proof's ID, linked to the file that proves it (relative to docs/). */
const proofLink = ({ id, file }) => (file ? `[\`${id}\`](${file})` : `\`${id}\``);

/** A mark linked to the file of the first proof of what it marks. */
const linked = (mark, proofs) => (proofs?.[0]?.file ? `[${mark}](${proofs[0].file})` : mark);

/** The matrix as Markdown: a table per group, then each refusal and not-applicable cell. */
export function capabilityMarkdown(records) {
  const lines = [
    "# Capabilities",
    "",
    "What every mark, Express recipe, and placement supports, as tests prove it.",
    "Generated by `npm run contracts:docs` from the declarations in",
    "[test/contracts/](../test/contracts/) and a complete passing run of every test",
    "suite (see Contract tests in [architecture.md](architecture.md)); do not edit.",
    "",
    `${STATES.works} works, proved by the test file it links to. ${STATES.unproved} supported, but not yet`,
    "proved: declared to work, with no test proving it yet, so the matrix does not",
    `vouch for it. ${STATES.refused} refused: asking for it fails with the message listed below,`,
    `which names an alternative that is tested to work. ${STATES.na} not applicable: the row has`,
    "nothing it would apply to, for the reason listed below. Refusals and reasons link to",
    "the tests proving them too.",
    "",
    `Of ${Object.values(records.totals).reduce((a, b) => a + b, 0)} cells: ${records.totals.works} proved to work, ` +
      `${records.totals.unproved} supported but not yet proved, ${records.totals.refused} refused, ` +
      `and ${records.totals.na} not applicable.`,
    "",
  ];
  const notes = [];
  const table = (title, rows, capabilities) => {
    lines.push(
      `| ${title} | ${capabilities.map((id) => records.capabilities[id].title).join(" | ")} |`,
    );
    lines.push(`| --- | ${capabilities.map(() => ":---:").join(" | ")} |`);
    for (const [row, { title: rowTitle, cells }] of Object.entries(rows)) {
      const marks = capabilities.map((id) => {
        const cell = cells[id];
        if (cell.state === "works") return linked(STATES.works, cell.proofs);
        if (cell.state === "unproved") return STATES.unproved;
        notes.push({ row: rowTitle, capability: records.capabilities[id].title, cell });
        return linked(`${STATES[cell.state]}${notes.length}`, cell.proofs);
      });
      lines.push(`| ${cellText(rowTitle ?? row)} | ${marks.join(" | ")} |`);
    }
    lines.push("");
  };
  for (const group of records.groups.filter((group) => group.for === undefined)) {
    lines.push(`## ${group.title}`, "");
    for (const id of group.capabilities)
      lines.push(`- **${records.capabilities[id].title}**: ${records.capabilities[id].works}`);
    lines.push("");
    table("Mark", records.marks, group.capabilities);
  }
  const express = records.express.capabilities;
  if (express.length > 0) {
    lines.push("## Express recipes", "");
    lines.push("Each recipe is all the marks it draws, proved together in Python.", "");
    // What recipes alone are asked, which no group of marks defines above.
    for (const group of records.groups.filter((group) => group.for === "express"))
      for (const id of group.capabilities)
        lines.push(`- **${records.capabilities[id].title}**: ${records.capabilities[id].works}`);
    lines.push("");
    table("Recipe", records.express.recipes, express);
  }
  lines.push("## Interaction in panels", "");
  const byCapability = new Map();
  for (const { id, file } of records.interaction.cells) {
    const [, capability, placement, ...variant] = id.split(".");
    if (!byCapability.has(capability)) byCapability.set(capability, new Map());
    const at = byCapability.get(capability);
    at.set(placement, [...(at.get(placement) ?? []), { variant: variant.join("."), file }]);
  }
  const placements = records.interaction.placements;
  lines.push(`| Interaction | ${placements.join(" | ")} |`);
  lines.push(`| --- | ${placements.map(() => ":---:").join(" | ")} |`);
  for (const [capability, at] of byCapability)
    lines.push(
      `| ${capability} | ${placements
        .map((placement) => {
          const variants = at.get(placement);
          if (!variants) return "";
          const works = linked(
            STATES.works,
            variants.filter(({ variant }) => !variant),
          );
          const extra = variants
            .filter(({ variant }) => variant)
            .map(({ variant, file }) => linked(variant, [{ file }]));
          return extra.length ? `${works} (also ${extra.join(", ")})` : works;
        })
        .join(" | ")} |`,
    );
  lines.push("");
  lines.push("## GPU paths", "", records.gpu.about, "");
  lines.push("| Path | Taken for | Proved by |", "| --- | --- | --- |");
  for (const { title, when, proofs } of Object.values(records.gpu.paths))
    lines.push(`| ${title} | ${cellText(when)} | ${proofs.map(proofLink).join(", ")} |`);
  lines.push("");
  lines.push("## Names across surfaces", "", records.api.conventions, "");
  lines.push(
    "Where a surface differs, and why (scripts/contracts/api.mjs checks each), by audit: " +
      "what it compares, the surface, and the option whose settings it reads, if any " +
      "(`mark rule python`: the rule mark's options in Python; `mark line python continuity " +
      "maxGap`: the settings of a line's continuity.maxGap there; `mark * helper`: what every " +
      "mark's helper shares; `settings ScalePadding hg.Pixels`: a settings type against the " +
      "Python class taking it).",
    "",
  );
  for (const [audit, kinds] of Object.entries(records.api.audits)) {
    lines.push(`- \`${audit}\``);
    for (const [kind, entries] of Object.entries(kinds))
      for (const [option, entry] of Object.entries(entries))
        lines.push(`  - ${differenceText(kind, option, entry)}`);
  }
  lines.push("");
  if (notes.length > 0) {
    lines.push("## Refused and not applicable", "");
    notes.forEach(({ row, capability, cell }, i) => {
      const text =
        cell.state === "refused"
          ? `refused: \`${cellText(cell.error.message)}\`. Instead: ${cell.alternative.text} (${cell.alternative.proofs.map(proofLink).join(", ")})`
          : `not applicable: ${cell.reason}`;
      lines.push(`${i + 1}. ${row}, ${capability}: ${text}`);
    });
    lines.push("");
  }
  return lines.map(escapeTags).join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { values } = parseArgs({ options: { check: { type: "boolean" } } });
  const result = checkContracts();
  if (result.errors.length > 0) {
    for (const error of result.errors) console.error(`  ${error}`);
    console.error(
      `generate-capabilities: the docs come from a complete passing run; ${result.errors.length} errors`,
    );
    process.exit(1);
  }
  const records = capabilityRecords(result);
  const written = {
    [JSON_PATH]: `${JSON.stringify(records, null, 2)}\n`,
    [MD]: capabilityMarkdown(records),
  };
  if (values.check) {
    const stale = Object.entries(written)
      .filter(([path, text]) => {
        try {
          return readFileSync(path, "utf8") !== text;
        } catch {
          return true;
        }
      })
      .map(([path]) => relative(root, path));
    if (stale.length > 0) {
      console.error(
        `generate-capabilities: ${stale.join(" and ")} are stale; run npm run contracts:docs`,
      );
      process.exit(1);
    }
    console.log("generate-capabilities: the docs are current");
  } else {
    for (const [path, text] of Object.entries(written)) writeFileSync(path, text);
    console.log(
      `generate-capabilities: wrote ${Object.keys(written)
        .map((p) => relative(root, p))
        .join(" and ")}`,
    );
  }
}
