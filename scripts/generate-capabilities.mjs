// Writes docs/capabilities.md and docs/capabilities.json from the contract
// declarations (test/contracts/) and a complete passing check of them
// (scripts/check-contracts.mjs: every suite, every browser engine), so the
// documented matrix says only what tests prove:
//
//   node scripts/generate-capabilities.mjs           write them
//   node scripts/generate-capabilities.mjs --check   fail if they are stale
//
// Neither holds anything of the run (revision, times, paths outside the
// repository), so they change only when what is proved changes.

import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parseArgs } from "node:util";
import { checkContracts } from "./check-contracts.mjs";
import { root } from "./contracts/source.mjs";

const MD = join(root, "docs/capabilities.md");
const JSON_PATH = join(root, "docs/capabilities.json");

const STATES = { works: "✓", unproved: "○", refused: "✗", na: "·" };

/** The test files proving each contract ID, relative to docs/. */
function proofFiles(executions) {
  const files = new Map();
  for (const { id, suite, test } of executions) {
    // Python's tests are named by module (tests.test_capabilities), Vitest's by path.
    const path =
      suite === "python"
        ? `python/${test.split("::")[0].replaceAll(".", "/")}.py`
        : test.split(" > ")[0];
    files.set(id, relative(join(root, "docs"), join(root, path)));
  }
  return files;
}

/**
 * The documented matrix: every cell with its state, details, and proof IDs,
 * and the file of each proof once, in `proofFiles`.
 */
export function capabilityRecords({ declarations, cells, proofs, executions }) {
  const files = proofFiles(executions);
  // The file of each proof the records cite; a proof that did not run has none.
  const cited = new Map();
  const cite = (id) => {
    if (files.has(id)) cited.set(id, files.get(id));
    return id;
  };
  // An unproved cell's awaited proof is none yet.
  const proofsOf = (cell) =>
    proofs.filter((proof) => proof.for === cell && !proof.unproved).map(({ id }) => cite(id));
  const tableOf = (table, rows) =>
    Object.fromEntries(
      Object.entries(rows).map(([row, { title, inventory }]) => [
        row,
        {
          title,
          inventory,
          cells: Object.fromEntries(
            cells
              .filter((cell) => cell.table === table && cell.row === row)
              .map(({ capability, state, error, alternative, reason }) => [
                capability,
                {
                  state,
                  ...(error && {
                    error,
                    alternative: { ...alternative, proofs: alternative.proofs.map(cite) },
                  }),
                  ...(reason && { reason }),
                  proofs: proofsOf(`${table} ${row} ${capability}`),
                },
              ]),
          ),
        },
      ]),
    );
  const { capabilities, marks, express, interaction } = declarations;
  // Every cell of the matrix, marks' and Express recipes', by state.
  const totals = Object.fromEntries(Object.keys(STATES).map((state) => [state, 0]));
  for (const { state } of cells) totals[state]++;
  const records = {
    about:
      "Generated by scripts/generate-capabilities.mjs from test/contracts/ and a complete passing run of every test suite; do not edit. Cells and GPU paths name their proofs by contract ID, and an interaction cell is proved by its ID with .engine; proofFiles lists each proof's test file (relative to docs/).",
    totals,
    groups: capabilities.groups,
    capabilities: capabilities.capabilities,
    marks: tableOf("marks", marks.rows),
    express: { capabilities: express.capabilities, recipes: tableOf("express", express.recipes) },
    interaction: {
      placements: interaction.placements,
      cells: interaction.cells.map((id) => {
        cite(`${id}.engine`);
        return id;
      }),
    },
    gpu: {
      about: capabilities.gpu.about,
      paths: Object.fromEntries(
        Object.entries(capabilities.gpu.paths).map(([path, { title, when, proofs: ids }]) => [
          path,
          { title, when, proofs: ids.map(cite) },
        ]),
      ),
    },
  };
  const byFile = new Map();
  for (const [id, file] of [...cited].sort(([a], [b]) => (a < b ? -1 : 1)))
    byFile.set(file, [...(byFile.get(file) ?? []), id]);
  records.proofFiles = Object.fromEntries([...byFile].sort(([a], [b]) => (a < b ? -1 : 1)));
  return records;
}

/** The records as JSON, each value on one line where it fits in 100 columns. */
export function capabilityJson(records) {
  const inline = (value) => {
    if (Array.isArray(value)) return `[${value.map(inline).join(", ")}]`;
    if (value !== null && typeof value === "object") {
      const entries = Object.entries(value).filter(([, v]) => v !== undefined);
      if (entries.length === 0) return "{}";
      return `{ ${entries.map(([k, v]) => `${JSON.stringify(k)}: ${inline(v)}`).join(", ")} }`;
    }
    return JSON.stringify(value);
  };
  const format = (value, indent) => {
    const line = inline(value);
    if (value === null || typeof value !== "object" || indent.length + line.length <= 100)
      return line;
    const inner = `${indent}  `;
    if (Array.isArray(value))
      return `[\n${value.map((v) => inner + format(v, inner)).join(",\n")}\n${indent}]`;
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    return `{\n${entries
      .map(([k, v]) => `${inner}${JSON.stringify(k)}: ${format(v, inner)}`)
      .join(",\n")}\n${indent}}`;
  };
  return `${format(records, "")}\n`;
}

const cellText = (text) => text.replaceAll("|", "\\|");

/** A line with what Markdown would read as HTML (`<Chart>`) written as text, outside code spans. */
const escapeTags = (line) =>
  line
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replaceAll("<", "&lt;")))
    .join("");

/** A proof's ID, linked to the file that proves it (relative to docs/). */
const proofLink = (id, fileOf) => (fileOf.has(id) ? `[\`${id}\`](${fileOf.get(id)})` : `\`${id}\``);

/** Links to the files of some proofs, each once, named by the file. */
const fileLinks = (ids, fileOf) =>
  [...new Set(ids.map((id) => fileOf.get(id)).filter(Boolean))]
    .map((file) => `[${file.split("/").pop()}](${file})`)
    .join(", ");

/**
 * The matrix as Markdown: a count per mark, then a table per group with its
 * capabilities' meanings and proving files, and its refusals and
 * not-applicable reasons as notes, one per alternative or reason.
 */
export function capabilityMarkdown(records) {
  const fileOf = new Map();
  for (const [file, ids] of Object.entries(records.proofFiles))
    for (const id of ids) fileOf.set(id, file);
  const total = Object.values(records.totals).reduce((a, b) => a + b, 0);
  const lines = [
    "# Capabilities",
    "",
    "What every mark, Express recipe, and placement supports, as tests prove it.",
    "Generated by `npm run contracts:docs` from the declarations in",
    "[test/contracts/](../test/contracts/) and a complete passing run of every test",
    "suite (see [Contracts](contributing.md#contracts)); do not edit.",
    "[capabilities.json](capabilities.json) has the same matrix with each cell's proofs.",
    "[test/contracts/api.json](../test/contracts/api.json) lists where option names differ",
    "between TypeScript, Python, and the adapters, and why.",
    "",
    `- ${STATES.works} works, proved by the test file listed with the capability.`,
    `- ${STATES.unproved} supported, but not yet proved: declared to work, with no test proving it yet.`,
    `- ${STATES.refused}1 refused: asking for it fails with note 1's message, which names an alternative tested to work.`,
    `- ${STATES.na}2 not applicable, for note 2's reason.`,
    "",
    `Of ${total} cells: ${records.totals.works} proved to work, ` +
      `${records.totals.unproved} supported but not yet proved, ${records.totals.refused} refused, ` +
      `and ${records.totals.na} not applicable.`,
    "",
  ];
  const sections = records.groups.filter((group) => group.for === undefined);
  const hasExpress = records.express.capabilities.length > 0;
  const slug = (title) =>
    title
      .toLowerCase()
      .replace(/[^a-z0-9 -]/g, "")
      .replaceAll(" ", "-");
  const contents = [
    "By mark",
    ...sections.map((group) => group.title),
    ...(hasExpress ? ["Express recipes"] : []),
    "Interaction in panels",
    "GPU paths",
  ];
  lines.push(contents.map((title) => `[${title}](#${slug(title)})`).join(" · "), "");

  lines.push("## By mark", "", `| Mark | ${Object.values(STATES).join(" | ")} |`);
  lines.push(
    `| --- | ${Object.keys(STATES)
      .map(() => "---:")
      .join(" | ")} |`,
  );
  for (const [row, { title, cells }] of Object.entries(records.marks)) {
    const counts = Object.keys(STATES).map(
      (state) => Object.values(cells).filter((cell) => cell.state === state).length,
    );
    lines.push(`| ${cellText(title ?? row)} | ${counts.join(" | ")} |`);
  }
  lines.push("");

  let noted = 0;
  // The files listed with each capability, which its notes need not repeat.
  const provedIn = new Map();
  const describe = (ids, rows) => {
    for (const id of ids) {
      const { title, works } = records.capabilities[id];
      const proved = Object.values(rows).flatMap(({ cells }) =>
        cells[id].state === "works" ? cells[id].proofs : [],
      );
      provedIn.set(id, new Set(proved.map((proof) => fileOf.get(proof)).filter(Boolean)));
      const files = fileLinks(proved, fileOf);
      lines.push(`- **${title}**: ${works}${files ? ` Proved in ${files}.` : ""}`);
    }
    lines.push("");
  };
  // A table of rows against capabilities, then its notes, numbered across
  // the page: one per refusal's alternative and per not-applicable reason.
  const table = (heading, rows, capabilities) => {
    const notes = new Map();
    lines.push(
      `| ${heading} | ${capabilities.map((id) => records.capabilities[id].title).join(" | ")} |`,
    );
    lines.push(`| --- | ${capabilities.map(() => ":---:").join(" | ")} |`);
    for (const [row, { title, cells }] of Object.entries(rows)) {
      const marks = capabilities.map((id) => {
        const cell = cells[id];
        if (cell.state === "works" || cell.state === "unproved") return STATES[cell.state];
        const key = `${cell.state} ${cell.state === "na" ? cell.reason : cell.alternative.text}`;
        if (!notes.has(key)) notes.set(key, { number: ++noted, uses: [] });
        const note = notes.get(key);
        note.uses.push({ row: title ?? row, capability: id, cell });
        return `${STATES[cell.state]}${note.number}`;
      });
      lines.push(`| ${cellText(title ?? row)} | ${marks.join(" | ")} |`);
    }
    lines.push("");
    if (notes.size === 0) return;
    for (const { number, uses } of notes.values()) {
      const [{ row, cell }] = uses;
      let text;
      if (cell.state === "na") text = `Not applicable: ${cell.reason}`;
      else {
        const messages = new Set(uses.map(({ cell }) => cell.error.message));
        const message = `\`${cellText(cell.error.message)}\``;
        text = `Refused: ${messages.size > 1 ? `${message} (for ${row})` : message}. Instead: ${cell.alternative.text}`;
      }
      // Proofs in files other than those listed with the note's capabilities.
      const listed = new Set(
        uses.flatMap(({ capability }) => [...(provedIn.get(capability) ?? [])]),
      );
      const ids = uses.flatMap(({ cell }) => [...cell.proofs, ...(cell.alternative?.proofs ?? [])]);
      const others = fileLinks(
        ids.filter((id) => !listed.has(fileOf.get(id))),
        fileOf,
      );
      lines.push(`- ${STATES[cell.state]}${number} ${text}${others ? ` (${others})` : ""}`);
    }
    lines.push("");
  };
  for (const group of sections) {
    lines.push(`## ${group.title}`, "");
    describe(group.capabilities, records.marks);
    table("Mark", records.marks, group.capabilities);
  }
  if (hasExpress) {
    lines.push("## Express recipes", "");
    lines.push("Each recipe is all the marks it draws, proved together in Python.", "");
    // What recipes alone are asked, which no group of marks defines above.
    const own = records.groups
      .filter((group) => group.for === "express")
      .flatMap((group) => group.capabilities);
    describe(own, records.express.recipes);
    table("Recipe", records.express.recipes, records.express.capabilities);
  }

  lines.push("## Interaction in panels", "");
  const byCapability = new Map();
  for (const id of records.interaction.cells) {
    const [, capability, placement, ...variant] = id.split(".");
    if (!byCapability.has(capability)) byCapability.set(capability, new Map());
    const at = byCapability.get(capability);
    at.set(placement, [...(at.get(placement) ?? []), variant.join(".")]);
  }
  const placements = records.interaction.placements;
  lines.push(`| Interaction | ${placements.join(" | ")} |`);
  lines.push(`| --- | ${placements.map(() => ":---:").join(" | ")} |`);
  for (const [capability, at] of byCapability)
    lines.push(
      `| ${capability} | ${placements
        .map((placement) => {
          const variants = at.get(placement);
          if (!variants) return "";
          const extra = variants.filter(Boolean);
          return extra.length ? `${STATES.works} (also ${extra.join(", ")})` : STATES.works;
        })
        .join(" | ")} |`,
    );
  lines.push("");
  const interactionFiles = fileLinks(
    records.interaction.cells.map((id) => `${id}.engine`),
    fileOf,
  );
  if (interactionFiles) lines.push(`Proved in ${interactionFiles}.`, "");

  lines.push("## GPU paths", "", records.gpu.about, "");
  lines.push("| Path | Taken for | Proved by |", "| --- | --- | --- |");
  for (const { title, when, proofs } of Object.values(records.gpu.paths))
    lines.push(
      `| ${title} | ${cellText(when)} | ${proofs.map((id) => proofLink(id, fileOf)).join(", ")} |`,
    );
  lines.push("");

  return lines.map(escapeTags).join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { values } = parseArgs({ options: { check: { type: "boolean" } } });
  const result = checkContracts();
  if (result.errors.length > 0) {
    for (const error of result.errors) console.error(`  ${error}`);
    console.error(
      `generate-capabilities: the docs come from a complete passing run; ${result.errors.length} errors`,
    );
    process.exit(1);
  }
  const records = capabilityRecords(result);
  const written = {
    [JSON_PATH]: capabilityJson(records),
    [MD]: capabilityMarkdown(records),
  };
  if (values.check) {
    const stale = Object.entries(written)
      .filter(([path, text]) => {
        try {
          return readFileSync(path, "utf8") !== text;
        } catch {
          return true;
        }
      })
      .map(([path]) => relative(root, path));
    if (stale.length > 0) {
      console.error(
        `generate-capabilities: ${stale.join(" and ")} are stale; run npm run contracts:docs`,
      );
      process.exit(1);
    }
    console.log("generate-capabilities: the docs are current");
  } else {
    for (const [path, text] of Object.entries(written)) writeFileSync(path, text);
    console.log(
      `generate-capabilities: wrote ${Object.keys(written)
        .map((p) => relative(root, p))
        .join(" and ")}`,
    );
  }
}
